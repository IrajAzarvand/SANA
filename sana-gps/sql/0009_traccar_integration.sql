-- SANA GPS schema migration 0009: Traccar synchronization and unknown-device review.
-- Apply as a database administrator after migrations 0001-0008.
BEGIN;
SET ROLE sana_user;

CREATE TABLE IF NOT EXISTS gps.traccar_unknown_device (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    traccar_device_id BIGINT NOT NULL,
    unique_id VARCHAR(128) NOT NULL UNIQUE,
    name VARCHAR(160) NOT NULL,
    traccar_status VARCHAR(32) NOT NULL DEFAULT 'unknown',
    first_seen_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    last_seen_at TIMESTAMPTZ NULL,
    last_synced_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    review_status VARCHAR(20) NOT NULL DEFAULT 'pending'
        CHECK (review_status IN ('pending', 'registered', 'rejected')),
    reviewed_at TIMESTAMPTZ NULL,
    metadata JSONB NOT NULL DEFAULT '{}'::jsonb
);
CREATE INDEX IF NOT EXISTS ix_traccar_unknown_review_status
    ON gps.traccar_unknown_device(review_status, last_synced_at DESC);
CREATE INDEX IF NOT EXISTS ix_traccar_unknown_last_seen
    ON gps.traccar_unknown_device(last_seen_at DESC);

GRANT SELECT, INSERT, UPDATE ON gps.traccar_unknown_device TO sana_user;
GRANT USAGE, SELECT ON SEQUENCE gps.traccar_unknown_device_id_seq TO sana_user;

COMMIT;
