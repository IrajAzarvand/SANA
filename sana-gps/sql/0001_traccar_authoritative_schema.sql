-- Canonical SANA GPS schema: Traccar owns all raw telemetry, positions, events,
-- trips, and geofences. SANA stores only Neshan match results linked to Traccar
-- position IDs, plus short-lived map viewer heartbeats.
-- Run after Django migrations and sql/0000_roles.sql.
-- This is safe for fresh databases and intentionally drops legacy duplicate GPS objects.
BEGIN;
SET ROLE sana_user;

-- Remove dependent derived tables before the raw-history tables they referenced.
DROP TABLE IF EXISTS gps.vehicle_geofence_state CASCADE;
DROP TABLE IF EXISTS gps.geofence_assignment CASCADE;
DROP TABLE IF EXISTS gps.geofence_version CASCADE;
DROP TABLE IF EXISTS gps.geofence CASCADE;
DROP TABLE IF EXISTS gps.trip CASCADE;
DROP TABLE IF EXISTS gps.event CASCADE;
DROP TABLE IF EXISTS gps.current_state CASCADE;
DROP TABLE IF EXISTS gps.location_history CASCADE;
DROP TABLE IF EXISTS gps.raw_packet CASCADE;
DROP TABLE IF EXISTS gps.traccar_unknown_device CASCADE;

DROP FUNCTION IF EXISTS gps.purge_device_data(BIGINT) CASCADE;
DROP FUNCTION IF EXISTS gps.register_detected_device_protocol(BIGINT, TEXT) CASCADE;
DROP FUNCTION IF EXISTS gps.prevent_trip_number_change() CASCADE;
DROP SEQUENCE IF EXISTS gps.trip_number_seq CASCADE;

-- Rebuild the Neshan match table using Traccar's immutable position ID.
-- The reset workflow intentionally discards old GPS rows.
DROP TABLE IF EXISTS gps.map_matched_position CASCADE;

-- Only road-matched coordinates and identifiers needed to associate them with
-- Traccar's immutable position/device IDs are retained in SANA.
CREATE TABLE gps.map_matched_position (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    traccar_position_id BIGINT NOT NULL UNIQUE,
    traccar_device_id BIGINT NOT NULL,
    device_id BIGINT NOT NULL REFERENCES public.fleet_device(id) ON DELETE CASCADE,
    device_time TIMESTAMPTZ NOT NULL,
    matched_latitude NUMERIC(10,7) NOT NULL CHECK (matched_latitude BETWEEN -90 AND 90),
    matched_longitude NUMERIC(10,7) NOT NULL CHECK (matched_longitude BETWEEN -180 AND 180),
    matched_geom geometry(Point, 4326) NOT NULL,
    match_provider VARCHAR(32) NOT NULL DEFAULT 'neshan',
    matched_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);
CREATE INDEX IF NOT EXISTS ix_map_matched_device_time
    ON gps.map_matched_position(device_id, device_time DESC);
CREATE INDEX IF NOT EXISTS ix_map_matched_device_matched_at
    ON gps.map_matched_position(device_id, matched_at DESC);

-- The watcher table is intentionally retained: Neshan requests are only made
-- while at least one map viewer has a non-expired heartbeat.
CREATE TABLE IF NOT EXISTS gps.map_matching_watchers (
    session_id TEXT PRIMARY KEY,
    user_id BIGINT NOT NULL,
    expires_at TIMESTAMPTZ NOT NULL,
    updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);
CREATE INDEX IF NOT EXISTS gps_map_matching_watchers_expires_idx
    ON gps.map_matching_watchers(expires_at);
GRANT SELECT, INSERT, UPDATE, DELETE ON gps.map_matching_watchers TO sana_user;
GRANT SELECT, INSERT, UPDATE, DELETE ON gps.map_matched_position TO sana_user;
GRANT USAGE, SELECT ON SEQUENCE gps.map_matched_position_id_seq TO sana_user;

REVOKE ALL ON ALL TABLES IN SCHEMA gps FROM PUBLIC;
REVOKE ALL ON ALL SEQUENCES IN SCHEMA gps FROM PUBLIC;
COMMIT;
