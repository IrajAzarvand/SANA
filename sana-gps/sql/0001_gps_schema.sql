-- SANA GPS schema migration 0001
-- Execute as a PostgreSQL administrator after Django migrations and 0000_roles.sql.
-- GPS tables and functions are owned by the single application role sana_user.
BEGIN;

DO $$ BEGIN
    IF NOT EXISTS (SELECT 1 FROM pg_extension WHERE extname = 'postgis') THEN
        RAISE EXCEPTION 'PostGIS must be installed by a database administrator before GPS migrations';
    END IF;
END $$;
-- Create all GPS objects as the one application role.
SET ROLE sana_user;
REVOKE ALL ON SCHEMA gps FROM PUBLIC;
GRANT USAGE ON SCHEMA gps TO sana_user;
GRANT USAGE, CREATE ON SCHEMA gps TO sana_user;

CREATE TABLE IF NOT EXISTS gps.raw_packet (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    device_id BIGINT NULL REFERENCES public.fleet_device(id) ON DELETE SET NULL,
    protocol VARCHAR(50) NOT NULL,
    fingerprint CHAR(64) NOT NULL,
    received_at TIMESTAMPTZ NOT NULL,
    payload BYTEA NOT NULL,
    metadata JSONB NOT NULL DEFAULT '{}'::jsonb,
    CONSTRAINT uq_raw_packet_device_fingerprint UNIQUE (device_id, fingerprint)
);
CREATE INDEX IF NOT EXISTS ix_raw_packet_received_at ON gps.raw_packet(received_at);
CREATE INDEX IF NOT EXISTS ix_raw_packet_device_received ON gps.raw_packet(device_id, received_at);

CREATE TABLE IF NOT EXISTS gps.location_history (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    device_id BIGINT NOT NULL REFERENCES public.fleet_device(id) ON DELETE RESTRICT,
    device_time TIMESTAMPTZ NOT NULL,
    server_received_at TIMESTAMPTZ NOT NULL,
    latitude NUMERIC(10,7) NULL,
    longitude NUMERIC(10,7) NULL,
    geom geometry(Point, 4326) NULL,
    gps_valid BOOLEAN NOT NULL DEFAULT FALSE,
    accuracy NUMERIC(10,3) NULL,
    speed NUMERIC(10,2) NULL,
    heading NUMERIC(6,2) NULL,
    altitude NUMERIC(12,2) NULL,
    motion BOOLEAN NULL,
    ignition BOOLEAN NULL,
    satellites SMALLINT NULL,
    battery_voltage NUMERIC(10,3) NULL,
    external_voltage NUMERIC(10,3) NULL,
    gsm_signal SMALLINT NULL,
    odometer NUMERIC(14,3) NULL,
    engine_hours NUMERIC(14,3) NULL,
    fuel_level NUMERIC(10,3) NULL,
    attributes JSONB NOT NULL DEFAULT '{}'::jsonb,
    CONSTRAINT ck_location_history_latitude CHECK (latitude IS NULL OR latitude BETWEEN -90 AND 90),
    CONSTRAINT ck_location_history_longitude CHECK (longitude IS NULL OR longitude BETWEEN -180 AND 180),
    CONSTRAINT ck_location_history_gps_position CHECK (
        (gps_valid AND latitude IS NOT NULL AND longitude IS NOT NULL AND geom IS NOT NULL)
        OR (NOT gps_valid AND latitude IS NULL AND longitude IS NULL AND geom IS NULL)
    ),
    CONSTRAINT ck_location_history_heading CHECK (heading IS NULL OR (heading >= 0 AND heading < 360))
);
CREATE INDEX IF NOT EXISTS ix_location_history_device_time ON gps.location_history(device_id, device_time);
CREATE INDEX IF NOT EXISTS ix_location_history_geom ON gps.location_history USING GIST(geom);

CREATE TABLE IF NOT EXISTS gps.current_state (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    device_id BIGINT NOT NULL UNIQUE REFERENCES public.fleet_device(id) ON DELETE CASCADE,
    device_time TIMESTAMPTZ NULL,
    server_received_at TIMESTAMPTZ NOT NULL,
    last_seen TIMESTAMPTZ NOT NULL,
    updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    latitude NUMERIC(10,7) NULL,
    longitude NUMERIC(10,7) NULL,
    geom geometry(Point, 4326) NULL,
    gps_valid BOOLEAN NOT NULL DEFAULT FALSE,
    last_valid_latitude NUMERIC(10,7) NULL,
    last_valid_longitude NUMERIC(10,7) NULL,
    last_valid_geom geometry(Point, 4326) NULL,
    last_valid_device_time TIMESTAMPTZ NULL,
    last_valid_server_received_at TIMESTAMPTZ NULL,
    last_valid_accuracy NUMERIC(10,3) NULL,
    accuracy NUMERIC(10,3) NULL,
    speed NUMERIC(10,2) NULL,
    heading NUMERIC(6,2) NULL,
    altitude NUMERIC(12,2) NULL,
    motion BOOLEAN NULL,
    ignition BOOLEAN NULL,
    satellites SMALLINT NULL,
    battery_voltage NUMERIC(10,3) NULL,
    external_voltage NUMERIC(10,3) NULL,
    gsm_signal SMALLINT NULL,
    odometer NUMERIC(14,3) NULL,
    engine_hours NUMERIC(14,3) NULL,
    fuel_level NUMERIC(10,3) NULL,
    attributes JSONB NOT NULL DEFAULT '{}'::jsonb,
    CONSTRAINT ck_current_state_latitude CHECK (latitude IS NULL OR latitude BETWEEN -90 AND 90),
    CONSTRAINT ck_current_state_longitude CHECK (longitude IS NULL OR longitude BETWEEN -180 AND 180),
    CONSTRAINT ck_current_state_gps_position CHECK (
        (gps_valid AND latitude IS NOT NULL AND longitude IS NOT NULL AND geom IS NOT NULL)
        OR (NOT gps_valid AND latitude IS NULL AND longitude IS NULL AND geom IS NULL)
    ),
    CONSTRAINT ck_current_state_heading CHECK (heading IS NULL OR (heading >= 0 AND heading < 360))
);
CREATE INDEX IF NOT EXISTS ix_current_state_geom ON gps.current_state USING GIST(geom);
CREATE INDEX IF NOT EXISTS ix_current_state_last_seen ON gps.current_state(last_seen);

CREATE TABLE IF NOT EXISTS gps.event (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    device_id BIGINT NOT NULL REFERENCES public.fleet_device(id) ON DELETE RESTRICT,
    type VARCHAR(80) NOT NULL,
    source VARCHAR(16) NOT NULL CHECK (source IN ('DEVICE', 'SANA', 'SYSTEM')),
    mode VARCHAR(16) NOT NULL CHECK (mode IN ('POINT', 'STATE')),
    occurred_at TIMESTAMPTZ NOT NULL,
    started_at TIMESTAMPTZ NULL,
    ended_at TIMESTAMPTZ NULL,
    device_time TIMESTAMPTZ NULL,
    server_received_at TIMESTAMPTZ NOT NULL,
    latitude NUMERIC(10,7) NULL,
    longitude NUMERIC(10,7) NULL,
    geom geometry(Point, 4326) NULL,
    gps_valid BOOLEAN NOT NULL DEFAULT FALSE,
    attributes JSONB NOT NULL DEFAULT '{}'::jsonb,
    telemetry_reference BIGINT NULL REFERENCES gps.location_history(id) ON DELETE SET NULL,
    raw_packet_reference BIGINT NULL REFERENCES gps.raw_packet(id) ON DELETE SET NULL,
    CHECK (ended_at IS NULL OR started_at IS NULL OR ended_at >= started_at)
);
CREATE INDEX IF NOT EXISTS ix_event_device_occurred ON gps.event(device_id, occurred_at);
CREATE INDEX IF NOT EXISTS ix_event_device_type_started ON gps.event(device_id, type, started_at);
CREATE UNIQUE INDEX IF NOT EXISTS uq_event_active_state ON gps.event(device_id, type)
    WHERE mode = 'STATE' AND ended_at IS NULL;

CREATE SEQUENCE IF NOT EXISTS gps.trip_number_seq AS BIGINT;
CREATE TABLE IF NOT EXISTS gps.trip (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    number BIGINT NOT NULL DEFAULT nextval('gps.trip_number_seq') UNIQUE,
    device_id BIGINT NOT NULL REFERENCES public.fleet_device(id) ON DELETE RESTRICT,
    status VARCHAR(16) NOT NULL CHECK (status IN ('ACTIVE', 'COMPLETED')),
    started_at TIMESTAMPTZ NOT NULL,
    ended_at TIMESTAMPTZ NULL,
    start_geom geometry(Point, 4326) NULL,
    end_geom geometry(Point, 4326) NULL,
    start_odometer NUMERIC(14,3) NULL,
    end_odometer NUMERIC(14,3) NULL,
    start_engine_hours NUMERIC(14,3) NULL,
    end_engine_hours NUMERIC(14,3) NULL,
    start_fuel_level NUMERIC(10,3) NULL,
    end_fuel_level NUMERIC(10,3) NULL,
    distance NUMERIC(14,3) NULL,
    max_speed NUMERIC(10,2) NULL,
    moving_duration BIGINT NULL,
    stopped_duration BIGINT NULL,
    unknown_duration BIGINT NULL,
    start_event_id BIGINT NULL REFERENCES gps.event(id) ON DELETE SET NULL,
    end_event_id BIGINT NULL REFERENCES gps.event(id) ON DELETE SET NULL,
    attributes JSONB NOT NULL DEFAULT '{}'::jsonb,
    CHECK (ended_at IS NULL OR ended_at >= started_at)
);
ALTER SEQUENCE gps.trip_number_seq OWNED BY gps.trip.number;
CREATE INDEX IF NOT EXISTS ix_trip_device_started ON gps.trip(device_id, started_at);
CREATE UNIQUE INDEX IF NOT EXISTS uq_trip_one_active_per_device ON gps.trip(device_id) WHERE status = 'ACTIVE';

CREATE TABLE IF NOT EXISTS gps.geofence (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name VARCHAR(160) NOT NULL,
    is_active BOOLEAN NOT NULL DEFAULT TRUE,
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    attributes JSONB NOT NULL DEFAULT '{}'::jsonb
);
CREATE TABLE IF NOT EXISTS gps.geofence_version (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    geofence_id BIGINT NOT NULL REFERENCES gps.geofence(id) ON DELETE RESTRICT,
    version INTEGER NOT NULL CHECK (version > 0),
    geom geometry(Geometry, 4326) NOT NULL,
    valid_from TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    valid_to TIMESTAMPTZ NULL,
    attributes JSONB NOT NULL DEFAULT '{}'::jsonb,
    UNIQUE (geofence_id, version),
    CHECK (valid_to IS NULL OR valid_to > valid_from)
);
CREATE INDEX IF NOT EXISTS ix_geofence_version_geom ON gps.geofence_version USING GIST(geom);
CREATE TABLE IF NOT EXISTS gps.geofence_assignment (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    geofence_id BIGINT NOT NULL REFERENCES gps.geofence(id) ON DELETE RESTRICT,
    vehicle_id BIGINT NOT NULL REFERENCES public.fleet_vehicle(id) ON DELETE RESTRICT,
    assigned_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    unassigned_at TIMESTAMPTZ NULL,
    attributes JSONB NOT NULL DEFAULT '{}'::jsonb,
    CHECK (unassigned_at IS NULL OR unassigned_at >= assigned_at)
);
CREATE INDEX IF NOT EXISTS ix_geofence_assignment_vehicle ON gps.geofence_assignment(vehicle_id, assigned_at);
CREATE TABLE IF NOT EXISTS gps.vehicle_geofence_state (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    vehicle_id BIGINT NOT NULL REFERENCES public.fleet_vehicle(id) ON DELETE RESTRICT,
    geofence_id BIGINT NOT NULL REFERENCES gps.geofence(id) ON DELETE RESTRICT,
    device_id BIGINT NOT NULL REFERENCES public.fleet_device(id) ON DELETE RESTRICT,
    inside BOOLEAN NOT NULL,
    changed_at TIMESTAMPTZ NOT NULL,
    updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    attributes JSONB NOT NULL DEFAULT '{}'::jsonb,
    UNIQUE (vehicle_id, geofence_id)
);

-- Trip's human-readable number is immutable after insert.
CREATE OR REPLACE FUNCTION gps.prevent_trip_number_change()
RETURNS trigger
LANGUAGE plpgsql
AS $$
BEGIN
    IF NEW.number IS DISTINCT FROM OLD.number THEN
        RAISE EXCEPTION 'gps.trip.number is immutable';
    END IF;
    RETURN NEW;
END;
$$;
DROP TRIGGER IF EXISTS trg_trip_number_immutable ON gps.trip;
CREATE TRIGGER trg_trip_number_immutable
BEFORE UPDATE OF number ON gps.trip
FOR EACH ROW EXECUTE FUNCTION gps.prevent_trip_number_change();

-- The application role owns these objects and has full control. Keep anonymous
-- access disabled on current and future GPS tables and sequences.
REVOKE ALL ON ALL TABLES IN SCHEMA gps FROM PUBLIC;
REVOKE ALL ON ALL SEQUENCES IN SCHEMA gps FROM PUBLIC;

-- Keep public access disabled for objects created in the GPS schema in the future.
ALTER DEFAULT PRIVILEGES FOR ROLE sana_user IN SCHEMA gps REVOKE ALL ON TABLES FROM PUBLIC;
ALTER DEFAULT PRIVILEGES FOR ROLE sana_user IN SCHEMA gps REVOKE ALL ON SEQUENCES FROM PUBLIC;

RESET ROLE;
COMMIT;
